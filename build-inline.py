#!/usr/bin/env python3
"""Copies content.js and main.js INTO index.html (between the inline markers at the end of <body>).
Why: on some Indian connections a separate request to the site can hang; when content.js/main.js hung, the menu,
videos and nav never started. Inlined, the scripts arrive with the page itself.
Edit content.js / main.js as usual, then run:  python3 build-inline.py  (and commit index.html too)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent
html = (root / "index.html").read_text()
block = "<!--inline-js:start (generated by build-inline.py from content.js + main.js; edit those files, not this block)-->\n"
for name in ("content.js", "main.js"):
    src = (root / name).read_text().replace("</script", "<\\/script")
    block += "<script>/* " + name + " */\n" + src + "\n</script>\n"
block += "<!--inline-js:end-->"
html2, n = re.subn(r"<!--inline-js:start.*?<!--inline-js:end-->", lambda m: block, html, flags=re.S)
assert n == 1, "inline markers not found in index.html"
(root / "index.html").write_text(html2)
print("inlined", len(block), "chars")
